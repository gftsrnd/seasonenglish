// @vitest-environment jsdom
import { cleanup, render, screen, waitFor, within } from "@testing-library/react";
import "@testing-library/jest-dom/vitest";
import { userEvent } from "@testing-library/user-event";
import { afterEach, describe, expect, it, vi } from "vitest";
import type { MonthFrameworkView, MonthlyOperatorOverviewView } from "@e4s/contracts";
import type { MonthlyIllustrationsView } from "../../api/operator.js";
import { MonthlyResourceEditor } from "./MonthlyResourceEditor.js";
import { OperatorMonths, type OperatorMonthsActions } from "./Months.js";
import { ToastProvider } from "../shared/design-system.js";
import { ModalProvider } from "../shared/ModalProvider.js";

// Pictures here are mocks (plain URLs); no image is ever generated by these tests.
type Resources = NonNullable<MonthFrameworkView["resources"]>;
const resources: Resources = {
  coreTerms: [
    { id: "a2-core-1", word: "budget", meaning: "ngân sách", type: "noun", ipa: "/ˈbʌdʒɪt/", source: "core_registry", component: "core" },
    { id: "a2-core-2", word: "approve", meaning: "phê duyệt", type: "verb", ipa: "/əˈpruːv/", source: "core_registry", component: "core" }
  ],
  supportTerms: [],
  grammarTopics: [],
  sounds: []
};
const view = (locked = false, overrides: Partial<MonthlyIllustrationsView> = {}): MonthlyIllustrationsView => ({
  running: false, available: true, model: "mock-model",
  images: [
    { coreTermId: "a2-core-1", word: "budget", meaning: "ngân sách", status: "ready", source: "ai", url: "/mock/budget.png", locked },
    { coreTermId: "a2-core-2", word: "approve", meaning: "phê duyệt", status: "missing", locked }
  ],
  ...overrides
});

function renderEditor(illustrationView: MonthlyIllustrationsView) {
  const onGenerate = vi.fn();
  const onUpload = vi.fn();
  const onRemove = vi.fn();
  render(<MonthlyResourceEditor cefr="A2" version={3} resources={resources} onSave={vi.fn()} onClose={vi.fn()} illustrations={{ view: illustrationView, onGenerate, onUpload, onRemove }} />);
  return { dialog: within(screen.getByRole("dialog", { name: "Sửa tay tài nguyên A2" })), onGenerate, onUpload, onRemove };
}

async function openCore(dialog: ReturnType<typeof within>, word: string) {
  const user = userEvent.setup();
  await user.click(dialog.getByText("Từ cốt lõi & từ mở rộng"));
  await user.click(dialog.getByText(word, { selector: ".monthly-resource-editor-word" }));
  return user;
}

describe("Manual resource editor: core-word pictures before approval", () => {
  afterEach(() => cleanup());

  it("lets the Operator redraw, upload or remove a word's picture inside the manual editor", async () => {
    const { dialog, onGenerate, onUpload, onRemove } = renderEditor(view());
    const user = await openCore(dialog, "budget");
    const tile = within(dialog.getByRole("group", { name: "Ảnh minh họa của budget" }));
    expect(tile.getByRole("img", { name: "Minh họa: budget" })).toHaveAttribute("src", "/mock/budget.png");
    expect(dialog.getByText(/không cần bấm Lưu bản nháp/u)).toBeInTheDocument();

    await user.click(tile.getByRole("button", { name: "Xóa ảnh của budget" }));
    expect(onRemove).toHaveBeenCalledWith("budget");

    const file = new File(["png"], "budget.png", { type: "image/png" });
    await user.upload(tile.getByLabelText("Tải ảnh cho budget"), file);
    expect(onUpload).toHaveBeenCalledWith("budget", file);

    await user.click(tile.getByRole("button", { name: "Sinh lại" }));
    await user.type(tile.getByLabelText("Gợi ý vẽ lại budget"), "a wallet");
    await user.click(tile.getByRole("button", { name: "Vẽ lại" }));
    expect(onGenerate).toHaveBeenCalledWith({ words: ["budget"], hint: "a wallet" });
  });

  it("offers no remove action for a word without a picture, but still allows upload and redraw", async () => {
    const { dialog } = renderEditor(view());
    await openCore(dialog, "approve");
    const tile = within(dialog.getByRole("group", { name: "Ảnh minh họa của approve" }));
    expect(tile.queryByRole("button", { name: /Xóa ảnh/u })).not.toBeInTheDocument();
    expect(tile.getByLabelText("Tải ảnh cho approve")).toBeInTheDocument();
    expect(tile.getByRole("button", { name: "Sinh lại" })).toBeInTheDocument();
  });

  it("hides every picture action once the pictures are locked by approval or while a job runs", async () => {
    const { dialog } = renderEditor(view(true));
    await openCore(dialog, "budget");
    const tile = within(dialog.getByRole("group", { name: "Ảnh minh họa của budget" }));
    expect(tile.getByRole("img", { name: "Minh họa: budget" })).toBeInTheDocument();
    for (const name of [/Xóa ảnh/u, /Sinh lại/u]) expect(tile.queryByRole("button", { name })).not.toBeInTheDocument();
    expect(tile.queryByLabelText("Tải ảnh cho budget")).not.toBeInTheDocument();
    cleanup();

    const running = renderEditor(view(false, { running: true }));
    await openCore(running.dialog, "budget");
    expect(within(running.dialog.getByRole("group", { name: "Ảnh minh họa của budget" })).queryByRole("button", { name: /Xóa ảnh/u })).not.toBeInTheDocument();
  });
});

describe("Months: picture editing wired into Sửa tay", () => {
  afterEach(() => cleanup());
  const monthWindow = { previous: "2026-10", current: "2026-11", next: "2026-12", writable: true };
  const framework = (status: "draft" | "approved"): MonthFrameworkView => ({ id: "framework-a2", cefr: "A2", version: 3, status, scopeHash: "monthly-abc", lessons: [], quality: { severe: [], light: [] }, resources });
  function renderMonths(status: "draft" | "approved", extra: Partial<OperatorMonthsActions> = {}) {
    const overview: MonthlyOperatorOverviewView = { systemDate: "2026-11-05", monthWindow, brief: null, frameworks: [framework(status)] };
    const actions: OperatorMonthsActions = {
      onSelectMonth: vi.fn(), onSelectLevel: vi.fn(), onSuggestBrief: vi.fn(), onSaveBrief: vi.fn(), onApproveBrief: vi.fn(), onGenerateFramework: vi.fn(),
      onSaveFramework: vi.fn(), onApproveFramework: vi.fn(), onSaveDay: vi.fn(), onGenerateDay: vi.fn(), onAcknowledge: vi.fn(), onApproveDay: vi.fn(),
      onCreateCorrection: vi.fn(), onSaveCorrection: vi.fn(), onAcknowledgeCorrection: vi.fn(), onApproveCorrection: vi.fn(),
      onSaveResources: vi.fn().mockResolvedValue(undefined),
      // An existing picture means the draft is not auto-started; generation itself is a mock.
      onLoadIllustrations: vi.fn().mockResolvedValue(view(status === "approved")),
      onGenerateIllustrations: vi.fn().mockResolvedValue({ started: true, count: 1 }),
      onUploadIllustration: vi.fn().mockResolvedValue({ images: [] }),
      onRemoveIllustration: vi.fn().mockResolvedValue({ images: [] }),
      ...extra
    };
    const rendered = render(<ModalProvider><ToastProvider><OperatorMonths month="2026-11" todayMonth="2026-11" cefr="A2" busy={false} overview={overview} actions={actions} /></ToastProvider></ModalProvider>);
    return { actions, panel: within(rendered.container.querySelector<HTMLElement>(".monthly-resources")!) };
  }

  it("shows the picture controls in the draft editor and removes a picture after confirmation", async () => {
    const { actions, panel } = renderMonths("draft");
    const user = userEvent.setup();
    await waitFor(() => expect(actions.onLoadIllustrations).toHaveBeenCalledWith("framework-a2"));
    await waitFor(() => expect(panel.getByRole("button", { name: /Ảnh minh họa/u })).toBeInTheDocument());
    await user.click(panel.getByRole("button", { name: "Sửa tay" }));
    const dialog = within(screen.getByRole("dialog", { name: "Sửa tay tài nguyên A2" }));
    await user.click(dialog.getByText("Từ cốt lõi & từ mở rộng"));
    await user.click(dialog.getByText("budget", { selector: ".monthly-resource-editor-word" }));
    const tile = within(dialog.getByRole("group", { name: "Ảnh minh họa của budget" }));
    await user.click(tile.getByRole("button", { name: "Xóa ảnh của budget" }));
    const confirm = await screen.findByRole("dialog", { name: "Xóa ảnh của “budget”?" });
    await user.click(within(confirm).getByRole("button", { name: "Xóa ảnh" }));
    await waitFor(() => expect(actions.onRemoveIllustration).toHaveBeenCalledWith("framework-a2", "budget"));
    expect(actions.onLoadIllustrations).toHaveBeenCalledTimes(2);
  });

  it("offers no manual edit, and so no picture editing, after approval", async () => {
    const { actions, panel } = renderMonths("approved");
    await waitFor(() => expect(actions.onLoadIllustrations).toHaveBeenCalled());
    expect(panel.queryByRole("button", { name: "Sửa tay" })).not.toBeInTheDocument();
    expect(screen.queryByRole("group", { name: /Ảnh minh họa của/u })).not.toBeInTheDocument();
  });
});
