import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { loadEnvFile } from "node:process";
import { AI_TASKS, createAiService, createAnthropicProvider } from "@e4s/ai";
import type { ContentWeekInput } from "@e4s/contracts";
import {
  generateWeeklyLessonAllLevelsPipeline,
  normalizeWeeklyLessonPlanBlueprint,
  prepareWeeklyLessonRetryState,
  WEEKLY_LESSON_PIPELINE_VERSION,
  type WeeklyLessonPipelineCheckpoint
} from "../src/modules/content/weekly-generation.js";

try {
  loadEnvFile(new URL("../../../.env", import.meta.url));
} catch {
  // Explicit process environment remains authoritative.
}

const args = new Map<string, string>();
for (let index = 2; index < process.argv.length; index += 2) {
  const key = process.argv[index];
  const value = process.argv[index + 1];
  if (key?.startsWith("--") && value) args.set(key.slice(2), value);
}
const inputPath = args.get("input");
const outputRoot = args.get("output-root");
if (!inputPath || !outputRoot) {
  throw new Error("Usage: --input <week-json> --output-root <directory>");
}
if (!process.env.ANTHROPIC_API_KEY || process.env.AI_PROVIDER !== "anthropic") {
  throw new Error("ANTHROPIC_AI_NOT_CONFIGURED");
}

const levels = ["A1", "A2", "B1", "B2", "C1"] as const;
const week = JSON.parse(await readFile(resolve(inputPath), "utf8")) as ContentWeekInput;
const absoluteOutputRoot = resolve(outputRoot);
const configuredTimeout = Number(process.env.AI_TIMEOUT_MS ?? 120_000);
const runner = createAiService({
  registry: AI_TASKS,
  provider: createAnthropicProvider({
    apiKey: process.env.ANTHROPIC_API_KEY,
    ...(process.env.ANTHROPIC_MODEL ? { model: process.env.ANTHROPIC_MODEL } : {})
  }),
  timeoutMs: Number.isFinite(configuredTimeout) && configuredTimeout > 0 ? configuredTimeout : 120_000,
  maxAttempts: 3,
  loadPrompt: async () => ""
});

const componentFile: Record<WeeklyLessonPipelineCheckpoint["component"], string> = {
  grammarClassification: "01-grammar-classification.json",
  objectives: "02-objectives.json",
  foundation: "03-foundation.json",
  vocabulary: "04-vocabulary.json",
  "skills.comprehension": "05-comprehension.json",
  "skills.languagePractice": "06-language-practice.json",
  "skills.speaking": "07-speaking.json",
  "skills.reviewer": "08-reviewer.json",
  assemble: "09-assemble.json"
};

const resumeStatesByLevel: Record<string, Partial<Record<number, WeeklyLessonPipelineCheckpoint["state"]>>> = {};
for (const level of levels) {
  resumeStatesByLevel[level] = {};
  for (let dayNumber = 1; dayNumber <= 5; dayNumber += 1) {
    const candidates: Array<{ savedAt: number; state: WeeklyLessonPipelineCheckpoint["state"] }> = [];
    for (const filename of Object.values(componentFile)) {
      try {
        const stored = JSON.parse(await readFile(resolve(absoluteOutputRoot, level, `day${dayNumber}`, filename), "utf8")) as WeeklyLessonPipelineCheckpoint & {
          status?: string;
          pipelineVersion?: string;
          savedAt?: string;
        };
        if (stored.status === "validated"
          && stored.pipelineVersion === WEEKLY_LESSON_PIPELINE_VERSION
          && stored.cefr === level
          && stored.dayNumber === dayNumber) {
          candidates.push({ savedAt: Date.parse(stored.savedAt ?? "") || 0, state: stored.state });
        }
      } catch {
        // A missing or obsolete checkpoint is regenerated by the component pipeline.
      }
    }
    const latest = candidates.sort((left, right) => right.savedAt - left.savedAt)[0];
    if (latest) resumeStatesByLevel[level]![dayNumber] = prepareWeeklyLessonRetryState(latest.state);
  }
}

await mkdir(absoluteOutputRoot, { recursive: true });
process.stdout.write(`${JSON.stringify({ status: "batch_started", levels })}\n`);
try {
  const normalizedBlueprint = await normalizeWeeklyLessonPlanBlueprint(
    week,
    { prompt: "Normalize the approved weekly plan into complete daily lesson blueprints." },
    runner
  );
  await writeFile(
    resolve(absoluteOutputRoot, "normalized-week.json"),
    `${JSON.stringify(normalizedBlueprint.week, null, 2)}\n`,
    "utf8"
  );
  const generated = await generateWeeklyLessonAllLevelsPipeline(
    normalizedBlueprint.week,
    { prompt: "Generate one complete CEFR-appropriate lesson component from the approved weekly plan." },
    runner,
    {
      levels,
      qualityProfile: "strict",
      resumeStatesByLevel,
      onProgress: (event) => process.stdout.write(`${JSON.stringify({ status: "progress", ...event })}\n`),
      onCheckpoint: async (checkpoint) => {
        const dayDirectory = resolve(absoluteOutputRoot, checkpoint.cefr, `day${checkpoint.dayNumber}`);
        await mkdir(dayDirectory, { recursive: true });
        const payload = {
          status: "validated",
          pipelineVersion: WEEKLY_LESSON_PIPELINE_VERSION,
          savedAt: new Date().toISOString(),
          ...checkpoint
        };
        await writeFile(resolve(dayDirectory, componentFile[checkpoint.component]), `${JSON.stringify(payload, null, 2)}\n`, "utf8");
      }
    }
  );
  for (const level of levels) {
    await mkdir(resolve(absoluteOutputRoot, level), { recursive: true });
    await writeFile(
      resolve(absoluteOutputRoot, level, "level-result.json"),
      `${JSON.stringify({ level, lessons: generated.lessonsByLevel[level] }, null, 2)}\n`,
      "utf8"
    );
  }
  await writeFile(
    resolve(absoluteOutputRoot, "cross-level-validation.json"),
    `${JSON.stringify(generated.crossLevelValidation, null, 2)}\n`,
    "utf8"
  );
  process.stdout.write(`${JSON.stringify({ status: "batch_completed", levels })}\n`);
} catch (error) {
  const candidate = error && typeof error === "object" ? error as Record<string, unknown> : {};
  const failure = {
    status: "batch_failed",
    failedAt: new Date().toISOString(),
    code: typeof candidate.code === "string" ? candidate.code : "AI_LEVEL_BATCH_FAILED",
    message: error instanceof Error ? error.message : String(error),
    failures: candidate.failures ?? [],
    issues: candidate.issues ?? []
  };
  await writeFile(resolve(absoluteOutputRoot, "batch-failure.json"), `${JSON.stringify(failure, null, 2)}\n`, "utf8");
  process.stderr.write(`${JSON.stringify(failure)}\n`);
  process.exitCode = 1;
}
